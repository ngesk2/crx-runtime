def generate_secrets_backup():
    """Generate encrypted backup of secrets."""
    import json
    from cryptography.fernet import Fernet
    
    # Generate encryption key
    key = Fernet.generate_key()
    cipher = Fernet(key)
    
    # Read .env file
    env_path = Path(__file__).parent.parent.parent.parent / 'config' / 'environments' / '.env'
    
    with open(env_path, 'r') as f:
        env_content = f.read()
    
    # Encrypt
    encrypted = cipher.encrypt(env_content.encode())
    
    # Save encrypted backup
    backup_path = Path(__file__).parent.parent.parent.parent / 'config' / 'environments' / '.env.backup.enc'
    
    with open(backup_path, 'wb') as f:
        f.write(encrypted)
    
    # Save encryption key separately
    key_path = Path(__file__).parent.parent.parent.parent / 'config' / 'environments' / '.env.key'
    
    with open(key_path, 'wb') as f:
        f.write(key)
    
    print(f"Encrypted backup saved to: {backup_path}")
    print(f"Encryption key saved to: {key_path}")
    print("\nIMPORTANT:")
    print("1. Store the encryption key separately from the backup")
    print("2. Do not commit either file to version control")
    print("3. Store both files in secure locations")

if __name__ == '__main__':
    if len(sys.argv) > 1 and sys.argv[1] == '--backup':
        generate_secrets_backup()
    else:
        generate_env_file()
