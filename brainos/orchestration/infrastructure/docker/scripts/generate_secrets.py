#!/usr/bin/env python3
"""
Secure Random Secret Generation Script
Generates cryptographically secure random secrets for all required environment variables
"""

import secrets
import string
import sys
from pathlib import Path

def generate_password(length=32, use_special=True):
    """Generate cryptographically secure random password."""
    alphabet = string.ascii_letters + string.digits
    if use_special:
        alphabet += "!@#$%^&*"
    return ''.join(secrets.choice(alphabet) for _ in range(length))

def generate_api_key(length=64):
    """Generate cryptographically secure random API key."""
    alphabet = string.ascii_letters + string.digits
    return ''.join(secrets.choice(alphabet) for _ in range(length))

def generate_jwt_secret(length=64):
    """Generate cryptographically secure random JWT secret."""
    alphabet = string.ascii_letters + string.digits
    return ''.join(secrets.choice(alphabet) for _ in range(length))

def generate_encryption_key(length=32):
    """Generate cryptographically secure random encryption key."""
    return secrets.token_hex(length)

